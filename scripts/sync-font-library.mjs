// Publishes font-library/ (the canonical, hand-editable source of embedded
// fonts) to both consumers: apps/editor (served statically + @font-face,
// browser) and services/render (registered with @napi-rs/canvas's
// GlobalFonts, so print exports use the same font the editor showed). Run
// this any time you add, rename, or remove a file under font-library/ —
// see README's "Adding fonts" section.
//
// font-library/<Family>/<weight>.<ext>  e.g. font-library/Inter/700.woff2
// <weight> must be a CSS font-weight number (400 = normal, 700 = bold).
//
// Run with: node scripts/sync-font-library.mjs

import { readdirSync, mkdirSync, rmSync, copyFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.join(ROOT, "font-library");
const FONT_EXTENSIONS = new Set([".woff2", ".woff", ".ttf", ".otf"]);
const FORMAT_BY_EXT = { ".woff2": "woff2", ".woff": "woff", ".ttf": "truetype", ".otf": "opentype" };

const TARGETS = [
  {
    fontsDir: path.join(ROOT, "apps/editor/public/fonts"),
    catalogFile: path.join(ROOT, "apps/editor/src/fontCatalog.generated.json"),
    cssFile: path.join(ROOT, "apps/editor/src/fonts.generated.css"),
  },
  {
    fontsDir: path.join(ROOT, "services/render/assets/fonts"),
    catalogFile: path.join(ROOT, "services/render/src/fontCatalog.generated.json"),
    cssFile: null,
  },
];

function scanCatalog() {
  const familyDirs = readdirSync(SOURCE_DIR, { withFileTypes: true }).filter((e) => e.isDirectory());
  const families = [];
  for (const familyEntry of familyDirs) {
    const family = familyEntry.name;
    const familyDir = path.join(SOURCE_DIR, family);
    const files = readdirSync(familyDir, { withFileTypes: true }).filter(
      (e) => e.isFile() && FONT_EXTENSIONS.has(path.extname(e.name).toLowerCase())
    );

    const weights = [];
    for (const file of files) {
      const ext = path.extname(file.name).toLowerCase();
      const weight = Number(path.basename(file.name, ext));
      if (!Number.isFinite(weight)) {
        console.warn(`Skipping ${family}/${file.name}: filename isn't a CSS font-weight number (e.g. 400.woff2).`);
        continue;
      }
      weights.push({ weight, fileName: file.name, format: FORMAT_BY_EXT[ext] });
    }
    weights.sort((a, b) => a.weight - b.weight);
    if (weights.length > 0) families.push({ family, weights });
  }
  families.sort((a, b) => a.family.localeCompare(b.family));
  return families;
}

function buildFontFaceCss(families) {
  const blocks = [];
  for (const { family, weights } of families) {
    for (const { weight, fileName, format } of weights) {
      blocks.push(
        `@font-face {\n` +
          `  font-family: "${family}";\n` +
          `  font-style: normal;\n` +
          `  font-weight: ${weight};\n` +
          `  font-display: swap;\n` +
          `  src: url("/fonts/${family}/${fileName}") format("${format}");\n` +
          `}`
      );
    }
  }
  return (
    "/* Generated by scripts/sync-font-library.mjs from font-library/ — do not hand-edit. */\n\n" +
    blocks.join("\n\n") +
    "\n"
  );
}

function publish(families) {
  for (const target of TARGETS) {
    rmSync(target.fontsDir, { recursive: true, force: true });
    for (const { family, weights } of families) {
      const destDir = path.join(target.fontsDir, family);
      mkdirSync(destDir, { recursive: true });
      for (const { fileName } of weights) {
        copyFileSync(path.join(SOURCE_DIR, family, fileName), path.join(destDir, fileName));
      }
    }
    writeFileSync(target.catalogFile, JSON.stringify(families, null, 2) + "\n");
    console.log(`wrote ${families.length} families -> ${path.relative(ROOT, target.catalogFile)}`);

    if (target.cssFile) {
      writeFileSync(target.cssFile, buildFontFaceCss(families));
      console.log(`wrote @font-face rules -> ${path.relative(ROOT, target.cssFile)}`);
    }
  }
}

const families = scanCatalog();
if (families.length === 0) {
  console.warn(`No font files found under ${path.relative(ROOT, SOURCE_DIR)}/<Family>/<weight>.{woff2,woff,ttf,otf} — nothing to publish.`);
} else {
  publish(families);
}
